#!/usr/bin/env python3
"""Offline precision/recall eval for missing_required_evidence_docs()."""

from __future__ import annotations

import argparse
import json
import sys
from dataclasses import dataclass, field
from pathlib import Path

# Allow running as `python scripts/eval_evidence_docs.py` from control-tower/
_ROOT = Path(__file__).resolve().parents[1]
if str(_ROOT) not in sys.path:
    sys.path.insert(0, str(_ROOT))

from configs.loader import (
    ApprovalThreshold,
    ProcessConfig,
    load_process,
)
from guardrails.evidence_docs import missing_required_evidence_docs

_DEFAULT_FIXTURE = _ROOT / "tests" / "fixtures" / "evidence_docs_eval.jsonl"
_DEFAULT_REPORT = _ROOT / "reports" / "evidence_docs_eval.md"


@dataclass
class CaseResult:
    id: str
    category: str
    expected: list[str]
    predicted: list[str]
    match: bool


@dataclass
class Metrics:
    cases: int = 0
    tp: int = 0
    fp: int = 0
    fn: int = 0
    tn: int = 0
    results: list[CaseResult] = field(default_factory=list)

    @property
    def precision(self) -> float:
        denom = self.tp + self.fp
        return self.tp / denom if denom else 1.0

    @property
    def recall(self) -> float:
        denom = self.tp + self.fn
        return self.tp / denom if denom else 1.0

    @property
    def f1(self) -> float:
        p, r = self.precision, self.recall
        return 2 * p * r / (p + r) if (p + r) else 1.0

    @property
    def fnr(self) -> float:
        denom = self.fn + self.tp
        return self.fn / denom if denom else 0.0

    @property
    def fpr(self) -> float:
        denom = self.fp + self.tn
        return self.fp / denom if denom else 0.0


def _resolve_config(row: dict) -> ProcessConfig:
    has_process = "process" in row
    has_inline = "required_evidence_docs" in row
    if has_process == has_inline:
        raise ValueError(
            f"{row.get('id', '?')}: provide exactly one of "
            "'process' or 'required_evidence_docs'"
        )
    if has_process:
        return load_process(row["process"])
    return ProcessConfig(
        process=f"eval_{row['id']}",
        allowed_tools=[],
        disallowed_tools=[],
        required_evidence_docs=list(row["required_evidence_docs"]),
        approval_threshold=ApprovalThreshold(risk_score_gte=60),
        knowledge_base_paths=[],
    )


def load_cases(path: Path) -> list[dict]:
    rows: list[dict] = []
    for line_no, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        text = line.strip()
        if not text or text.startswith("#"):
            continue
        try:
            rows.append(json.loads(text))
        except json.JSONDecodeError as exc:
            raise ValueError(f"{path}:{line_no}: invalid JSONL") from exc
    return rows


def evaluate(cases: list[dict]) -> Metrics:
    metrics = Metrics()
    for row in cases:
        config = _resolve_config(row)
        chunk_ids = list(row.get("chunk_ids") or [])
        expected = list(row.get("expected_missing") or [])
        predicted = missing_required_evidence_docs(config, chunk_ids)

        expected_set = set(expected)
        predicted_set = set(predicted)
        required = set(config.required_evidence_docs)

        metrics.tp += len(predicted_set & expected_set)
        metrics.fp += len(predicted_set - expected_set)
        metrics.fn += len(expected_set - predicted_set)
        # Gold-present labels among required docs that were not predicted missing.
        gold_present = required - expected_set
        metrics.tn += len(gold_present - predicted_set)

        metrics.cases += 1
        metrics.results.append(
            CaseResult(
                id=str(row["id"]),
                category=str(row.get("category", "")),
                expected=sorted(expected),
                predicted=sorted(predicted),
                match=expected_set == predicted_set,
            )
        )
    return metrics


def _fmt_list(items: list[str]) -> str:
    if not items:
        return "∅"
    return ", ".join(items)


def render_markdown(metrics: Metrics) -> str:
    lines = [
        "# Evidence docs eval",
        "",
        (
            "Offline micro-averaged precision/recall for "
            "`missing_required_evidence_docs()` "
            "(positive class = doc reported missing)."
        ),
        "",
        (
            "Regenerated by `scripts/eval_evidence_docs.py` — "
            "do not edit by hand; CI fails if this file drifts."
        ),
        "",
        "## Summary",
        "",
        "| Metric | Value |",
        "| --- | --- |",
        f"| Cases | {metrics.cases} |",
        f"| TP | {metrics.tp} |",
        f"| FP | {metrics.fp} |",
        f"| FN | {metrics.fn} |",
        f"| TN | {metrics.tn} |",
        f"| Precision | {metrics.precision:.4f} |",
        f"| Recall | {metrics.recall:.4f} |",
        f"| F1 | {metrics.f1:.4f} |",
        f"| False-negative rate | {metrics.fnr:.4f} |",
        f"| False-positive rate | {metrics.fpr:.4f} |",
        "",
        "## Per-case",
        "",
        "| id | category | expected_missing | predicted_missing | match |",
        "| --- | --- | --- | --- | --- |",
    ]
    for r in metrics.results:
        match = "yes" if r.match else "no"
        lines.append(
            f"| {r.id} | {r.category} | {_fmt_list(r.expected)} | "
            f"{_fmt_list(r.predicted)} | {match} |"
        )
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Eval missing_required_evidence_docs precision/recall"
    )
    parser.add_argument(
        "--fixture",
        type=Path,
        default=_DEFAULT_FIXTURE,
        help="Path to labeled JSONL fixture",
    )
    parser.add_argument(
        "--write",
        type=Path,
        default=_DEFAULT_REPORT,
        help="Markdown report output path",
    )
    args = parser.parse_args(argv)

    fixture = args.fixture if args.fixture.is_absolute() else _ROOT / args.fixture
    write_path = args.write if args.write.is_absolute() else _ROOT / args.write

    cases = load_cases(fixture)
    metrics = evaluate(cases)
    report = render_markdown(metrics)

    write_path.parent.mkdir(parents=True, exist_ok=True)
    write_path.write_text(report, encoding="utf-8", newline="\n")

    print(
        f"cases={metrics.cases} "
        f"P={metrics.precision:.4f} R={metrics.recall:.4f} F1={metrics.f1:.4f} "
        f"FNR={metrics.fnr:.4f} FPR={metrics.fpr:.4f} "
        f"wrote={write_path}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
